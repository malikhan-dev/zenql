// Is used to collect items. returns an array of items. ([]T)
func (op *CollectionCompiledQueryable[T]) Collect() []T {

	var result []T

	result = contracts.AllocateSlice[T](len(*op.Items))

	skipLimit, takeLimit := op.Page.Skip, op.Page.Limit

	var skipCount int

	skipCount = 0

	var HasUpdate bool

	var SortDescending bool

	var UpdateFunc func(T) T

	var FilterFunc func(T) bool

	var HasSort bool

	var SortFunc func(T, T) bool

	var resultCounter int

	resultCounter = 0

	var wg sync.WaitGroup

	wg.Add(2)

	var slice []T

	slice = *op.Items

	go func() {

		HasSort, SortDescending, SortFunc = extract_sort_meta(op.Operators)

		if HasSort {
			sort.Slice(slice, func(i, j int) bool {
				if SortDescending {
					return SortFunc(slice[j], slice[i])
				}
				return SortFunc(slice[i], slice[j])
			})

		}

		defer wg.Done()

	}()

	go func() {
		HasUpdate, UpdateFunc = extract_update_meta(op.Operators)
		FilterFunc = extract_filter_meta(op.Operators)
		defer wg.Done()
	}()

	wg.Wait()

	hasTake := takeLimit != -1

	for _, item := range slice {

		keep := true

		keep = FilterFunc(item)

		if keep {

			if skipCount < skipLimit {
				skipCount++
				continue
			}

			if hasTake {
				if resultCounter == takeLimit {
					return result
				}
			}
			if HasUpdate {
				item = UpdateFunc(item)
			}
			result = append(result, item)
			resultCounter++
		}
	}
	return result

}

// Is used to collect a specific item inside a relational collection (usually a parent child relationship). returns an item with the type of T. requires one function to search for the node and another one to describe the relationship between parents and childs.
func (op *CollectionCompiledQueryable[T]) FindParentNode(NodeLocator func(T) bool, Criteria func(child T, parent T) bool) T {

	var result []T

	var TargetNode T

	result = contracts.AllocateSlice[T](len(*op.Items))

	for _, item := range *op.Items {

		keep := true

		for _, operator := range op.Operators {

			keep = CoreFilter(operator, item)

			if !keep {
				break
			}
		}

		if keep {

			if NodeLocator(item) {
				TargetNode = item
			}
			result = append(result, item)

		}
	}

	var value T
	for _, val := range result {
		if Criteria(TargetNode, val) {
			value = val
			break
		}
	}

	return value
}

// Is used to collect the root node  inside a relational collection (usually a parent child relationship). returns an item with the type of T. requires one function to locate the starting node. another function that can describe the relationship. and a third function for comparing between the nodes( a less function ).
func (op *CollectionCompiledQueryable[T]) FindRootNode(Start func(T) bool, Link func(child T, parent T) bool, Less func(T, T) bool) T {

	var result []T

	var TargetNode T

	result = contracts.AllocateSlice[T](len(*op.Items))

	for _, item := range *op.Items {

		keep := true

		for _, operator := range op.Operators {

			keep = CoreFilter(operator, item)

			if !keep {
				break
			}
		}

		if keep {

			if Start(item) {
				TargetNode = item
			}
			result = append(result, item)

		}
	}

	sort.Slice(result, func(i, j int) bool {
		return Less(result[j], result[i])
	})

	for _, val := range result {

		if Link(TargetNode, val) {
			TargetNode = val
		}

	}

	return TargetNode
}

// Is used to walk throught root node inside a relational collection (usually a parent child relationship). it streams the path to root node. requires one function to locate the starting node. another function that can describe the relationship. and a third function for comparing between the nodes( a less function ).
func (op *CollectionCompiledQueryable[T]) TraverseRootNode(Start func(T) bool, Link func(child T, parent T) bool, Less func(T, T) bool, ctx context.Context) <-chan T {

	var result []T

	var TargetNode T

	result = contracts.AllocateSlice[T](len(*op.Items))

	for _, item := range *op.Items {

		keep := true

		for _, operator := range op.Operators {

			keep = CoreFilter(operator, item)

			if !keep {
				break
			}
		}

		if keep {

			if Start(item) {
				TargetNode = item
			}
			result = append(result, item)

		}
	}

	sort.Slice(result, func(i, j int) bool {
		return Less(result[j], result[i])
	})

	out := make(chan T, 1)

	go func() {

		for _, val := range result {

			if Link(TargetNode, val) {
				select {
				case <-ctx.Done():
					break
				case out <- val:
					TargetNode = val
				}
			}
		}
		defer close(out)

	}()

	return out
}

// Is used to collect items which is about to be grouped.
func (op *GroupCompiledQueryable[K, T]) Collect() *GroupedQueryable[K, T] {

	var result GroupedQueryable[K, T]

	compiledResult := op.CompiledQueryable.Compiler()

	result.Items = contracts.AllocateMap[K, T](len(compiledResult))

	var LocatedKey K

	for _, item := range compiledResult {

		LocatedKey = op.PropLocator(item)

		result.Items[LocatedKey] = append(result.Items[LocatedKey], item)
	}

	return &result
}

func extract_update_meta[T any](op []contracts.ZenqlOperator[T]) (bool, func(T) T) {

	var HasUpdate bool
	var UpdateFunc func(T) T

	for _, op := range op {

		if op.OperatorType == UpdateCollection {
			HasUpdate = true
			UpdateFunc = op.Update.Update
			break
		}
	}
	return HasUpdate, UpdateFunc

}

func extract_filter_meta[T any](op []contracts.ZenqlOperator[T]) func(T) bool {

	for _, op := range op {
		if op.OperatorType == WhereCollection {
			return op.Filter.Filter

		}
	}
	return func(item T) bool {
		return true
	}
}

func extract_sort_meta[T any](op []contracts.ZenqlOperator[T]) (bool, bool, func(T, T) bool) {

	for _, op := range op {
		if op.OperatorType == SortCollection {
			return true, op.Sort.IsDescending(), op.Sort.Sort

		}
	}
	return false, false, func(item T, item2 T) bool {
		return true
	}
}
